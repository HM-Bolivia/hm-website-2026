#!/usr/bin/env node
// Regenerates the speakers list in index.html from a pretalx speakers export (JSON).
//
//   npm run speakers -- ~/Downloads/hackmeeting-2026-la-paz_speakers.json
//
// The HTML is static (written between the speakers:start/end markers) so the content doesn't depend on
// JS. Avatars are downloaded to src/assets/speakers/ so Vite hashes them and we don't hotlink pretalx;
// existing files are kept, delete one to download it again. They're cropped square and shrunk with
// ImageMagick 7 (pretalx serves 1024 px; the cards show them at 112 px, 240 covers 2x screens).
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const htmlPath = path.join(root, 'index.html');
const avatarDir = path.join(root, 'src/assets/speakers');
const START = '<!-- speakers:start (generated by scripts/build-speakers.mjs, do not edit by hand) -->';
const END = '<!-- speakers:end -->';

// The pretalx export lists every proposal a speaker sent, not only the accepted ones. Titles here are
// left out of the page. (Exporting only accepted talks from pretalx would make this list unnecessary.)
const notAccepted = new Set([
  '¿Pensar o promptear?',
  'Dark Data el nuevo problema?',
  'De usuario estándar a Domain Admin: La "vieja confiable" para comprometer Active Directory',
]);

const input = process.argv[2];
if (!input) {
  console.error('Usage: npm run speakers -- <pretalx-speakers.json>');
  process.exit(1);
}

const speakers = JSON.parse(await readFile(input, 'utf8'))
  .map((s) => ({
    id: s.ID,
    name: s.Nombre.trim(),
    bio: (s['Biografía'] ?? '').trim(),
    image: s.Imagen,
    talks: (s['Títulos de propuestas'] ?? []).filter((t) => !notAccepted.has(t.trim())),
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'es', { sensitivity: 'base' }));

await mkdir(avatarDir, { recursive: true });
for (const s of speakers) {
  if (!s.image) continue;
  const ext = path.extname(new URL(s.image).pathname) || '.webp';
  const file = `${s.id}${ext}`;
  s.avatar = `/src/assets/speakers/${file}`;
  const dest = path.join(avatarDir, file);
  if (await exists(dest)) continue;
  const res = await fetch(s.image);
  if (!res.ok) throw new Error(`${s.image}: HTTP ${res.status}`);
  await writeFile(dest, Buffer.from(await res.arrayBuffer()));
  execFileSync('magick', [dest, '-strip', '-resize', '240x240^', '-gravity', 'center', '-extent', '240x240', '-quality', '82', dest]);
  console.log(`downloaded ${file} (${s.name})`);
}

const talkCount = speakers.reduce((n, s) => n + s.talks.length, 0);
const indent = (n) => ' '.repeat(n);

const cards = speakers.map((s) => {
  const photo = s.avatar
    ? `<img src="${s.avatar}" alt="" width="112" height="112" loading="lazy" />`
    : `<span class="speaker-initials" aria-hidden="true">${escape(initials(s.name))}</span>`;
  const talks = s.talks.map((t) => `${indent(18)}<li>${escape(t.trim())}</li>`).join('\n');
  const bio = s.bio
    ? `
${indent(16)}<details class="speaker-bio">
${indent(18)}<summary>cat bio.txt</summary>
${indent(18)}<p>${escape(s.bio).replace(/\r?\n/g, '<br />')}</p>
${indent(16)}</details>`
    : '';
  return `${indent(12)}<li class="speaker">
${indent(14)}<div class="speaker-photo">${photo}</div>
${indent(14)}<div class="speaker-body">
${indent(16)}<h3 class="speaker-name">${escape(s.name)}</h3>
${indent(16)}<ul class="speaker-talks">
${talks}
${indent(16)}</ul>${bio}
${indent(14)}</div>
${indent(12)}</li>`;
});

const block = `${START}
${indent(10)}<p class="speakers-count"><span>${speakers.length}</span> ponentes · <span>${talkCount}</span> charlas</p>
${indent(10)}<ul class="speakers">
${cards.join('\n')}
${indent(10)}</ul>
${indent(10)}${END}`;

const html = await readFile(htmlPath, 'utf8');
const from = html.indexOf(START);
const to = html.indexOf(END);
if (from === -1 || to === -1) throw new Error('speakers markers not found in index.html');
await writeFile(htmlPath, html.slice(0, from) + block + html.slice(to + END.length));
console.log(`${speakers.length} speakers, ${talkCount} talks written to index.html`);

function initials(name) {
  // Letters only, so handles with emojis or digits still get a sensible placeholder.
  const words = name.split(/\s+/).map((w) => w.replace(/[^\p{L}]/gu, '')).filter(Boolean);
  return (words.length > 1 ? words[0][0] + words[1][0] : (words[0] ?? '?').slice(0, 2)).toUpperCase();
}

function escape(text) {
  return text.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
}

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}
